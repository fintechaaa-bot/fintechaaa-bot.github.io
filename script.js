let lang = localStorage.getItem("portfolio-lang") || "ko";

function applyTranslations() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) el.innerHTML = translations[lang][key];
  });
  document.getElementById("currentLang").textContent = lang.toUpperCase();
  document.title = lang === "ko" ? "홍길동 | Frontend Developer" : `Hong Gildong | Frontend Developer`;
  renderProjects();
}

function renderProjects() {
  const list = document.getElementById("projectsList");
  list.innerHTML = projects.map((p, i) => `
    <article class="project-item reveal" data-index="${i}">
      <div class="project-no">${p.no}</div>
      <div><h3 class="project-title">${p.title[lang]}</h3><p class="project-meta">${p.date[lang]}</p></div>
      <div class="project-arrow">↗</div>
    </article>
  `).join("");
  list.querySelectorAll(".project-item").forEach(item => item.addEventListener("click", () => openProject(+item.dataset.index)));
  observeReveals();
}

function openProject(index) {
  const p = projects[index];
  document.getElementById("modalNumber").textContent = p.no;
  document.getElementById("modalTitle").textContent = p.title[lang];
  document.getElementById("modalMeta").textContent = p.date[lang];
  document.getElementById("modalTags").innerHTML = p.tags.map(t => `<span class="tag">${t}</span>`).join("");
  document.getElementById("modalDescription").textContent = p.desc[lang];
  document.getElementById("modalBullets").innerHTML = p.bullets[lang].map(b => `<li>${b}</li>`).join("");
  document.getElementById("projectModal").classList.add("open");
  document.getElementById("projectModal").setAttribute("aria-hidden","false");
  document.body.style.overflow = "hidden";
}
function closeProject() {
  document.getElementById("projectModal").classList.remove("open");
  document.getElementById("projectModal").setAttribute("aria-hidden","true");
  document.body.style.overflow = "";
}

document.getElementById("modalClose").addEventListener("click", closeProject);
